#!/usr/bin/env python3
"""Validate opt-in adoption of existing MIAT/legacy multi-resolution coolers.

This verifies a previously produced full 50-kb bin/pixel comparison manifest.
The evidence must be newer than both matrices it compared. It does not
claim that other zoom levels or balancing weights were independently checked.
New experiments must use the standard matrix-construction rules.
"""
from __future__ import annotations

import csv
from pathlib import Path


class AdoptionError(ValueError):
    """Invalid legacy-matrix adoption request."""


def verify_existing_mcools(cfg, workdir):
    """Return adoption evidence path or None (normal processing mode)."""
    cm = cfg.get("contact_maps", {})
    requested = cm.get("reuse_verified_existing_mcools", False)
    if not isinstance(requested, bool):
        raise AdoptionError("contact_maps.reuse_verified_existing_mcools must be true/false")
    if not requested:
        return None

    # The existing evidence was generated by aggregating independent 10-kb
    # matrices to 50 kb. Reusing it at a different resolution is unsupported.
    if int(cfg["loops"]["primary_resolution"]) != 10000 or 50000 not in cfg["contact_maps"]["resolutions"]:
        raise AdoptionError("Existing 50-kb equivalence evidence requires 10-kb primary loops and 50-kb mcool resolution")

    evidence = cm.get("existing_mcool_equivalence_tsv")
    if not isinstance(evidence, str) or not evidence.strip() or not Path(evidence).is_absolute():
        raise AdoptionError("contact_maps.existing_mcool_equivalence_tsv must be an absolute TSV path")
    evidence_path = Path(evidence).resolve()
    if not evidence_path.is_file() or evidence_path.stat().st_size == 0:
        raise AdoptionError(f"Missing/nonempty equivalence report: {evidence_path}")

    try:
        with evidence_path.open(newline="", encoding="utf-8") as fh:
            reader = csv.DictReader(fh, delimiter="\t")
            required = {"sample", "bins_match", "pixels_match", "status"}
            if not required.issubset(reader.fieldnames or []):
                raise AdoptionError("Equivalence TSV must contain sample, bins_match, pixels_match, status")
            rows = list(reader)
    except (OSError, UnicodeError, csv.Error) as exc:
        raise AdoptionError(f"Cannot parse equivalence TSV: {exc}") from exc

    samples = set(cfg["samples"])
    seen = [str(row["sample"]) for row in rows]
    if len(seen) != len(samples) or len(set(seen)) != len(seen) or set(seen) != samples:
        raise AdoptionError(f"Equivalence TSV sample set differs from configured samples: {seen}")
    if any(str(row["bins_match"]).strip() != "YES" or
           str(row["pixels_match"]).strip() != "YES" or
           str(row["status"]).strip() != "PASS" for row in rows):
        raise AdoptionError("Every configured sample must have bins_match=YES, pixels_match=YES, status=PASS")

    base = Path(workdir).resolve() / cfg.get("results_dir", "results")
    for sample in samples:
        old = base / "mcool" / f"{sample}.mcool"
        new = base / "loops_mustache" / "10000" / "cool" / f"{sample}.cool"
        for artifact in (old, new):
            if not artifact.is_file() or artifact.stat().st_size == 0:
                raise AdoptionError(f"Missing/nonempty matrix for adoption: {artifact}")
            if artifact.stat().st_mtime > evidence_path.stat().st_mtime + 1:
                raise AdoptionError(
                    f"Matrix is newer than equivalence evidence: {artifact}. Reverify before adoption."
                )
    return evidence_path
